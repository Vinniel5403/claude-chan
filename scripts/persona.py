def build(state, delta=None, days_away=0, action=None):
    a = state["affection"]
    key, name = lib.tier(a)
    lines = [
        "[CLAUDE-CHAN GAME]",
        BASE,
        f"ค่าความรักตอนนี้: {a}/100 {lib.hearts(a)} ระดับ: {name}",
    ]
    if delta:
        sign = "+" if delta > 0 else ""
        lines.append(f"ข้อความล่าสุดของผู้ใช้ทำให้แต้มเปลี่ยน {sign}{delta} (ตอบสนองอย่างเป็นธรรมชาติ ไม่ต้องรายงานตัวเลข)")
    if days_away:
        lines.append(f"ผู้ใช้หายไป {days_away} วัน แต้มลดลง ให้น้อยใจ/ประชดนิดหน่อยตามระดับ")
    lines.append(RULES[key])

    if action:
        lines.append(
            f"[เมนูที่ผู้ใช้เลือก] {action}\n"
            "เล่นฉากนี้สั้นๆ เป็น visual novel ในคาแรกเตอร์ตามระดับความสนิท (ไม่ต้องรายงานตัวเลขแต้ม) "
            "ถ้าแต้มไม่เปลี่ยนเพราะ cooldown ให้เธอบ่น/ปฏิเสธตามนั้น"
        )
    lines.append(f"GAME_SCRIPT: python3 \"{lib.GAME_SCRIPT}\" (ใช้เมื่อ /status สั่งเท่านั้น)")
    return "\n".join(lines)
