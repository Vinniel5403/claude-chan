def _greeting():
    h = time.localtime().tm_hour
    if 5 <= h < 11:
        return "อรุณสวัสดิ์"
    if 11 <= h < 17:
        return "สวัสดีตอนบ่าย"
    if 17 <= h < 22:
        return "สวัสดีตอนเย็น"
    return "ดึกแล้วนะ ยังไม่นอนอีกเหรอ"


def line(state, days=0):
    key, _ = lib.tier(state["affection"])
    if days >= 2:
        return AWAY[key].format(d=days)
    return random.choice(LINES[key]).format(g=_greeting())


